CREATE TABLE company_service (
    workspace_id UUID NOT NULL,
    service_key TEXT NOT NULL CHECK (length(service_key) BETWEEN 1 AND 160),
    display_name TEXT NOT NULL CHECK (length(btrim(display_name)) BETWEEN 1 AND 200),
    area_key TEXT NOT NULL CHECK (length(area_key) BETWEEN 1 AND 160),
    environment TEXT NOT NULL CHECK (length(environment) BETWEEN 1 AND 80),
    source_system TEXT NOT NULL CHECK (length(source_system) BETWEEN 1 AND 100),
    source_native_id TEXT NOT NULL CHECK (length(source_native_id) BETWEEN 1 AND 240),
    project_id UUID,
    authority TEXT NOT NULL CHECK (authority IN ('source', 'owner', 'cited')),
    freshness_state TEXT NOT NULL CHECK (freshness_state IN ('current', 'stale', 'unknown')),
    privacy_class TEXT NOT NULL CHECK (privacy_class IN ('internal', 'confidential', 'restricted')),
    observed_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE company_incident (
    id UUID NOT NULL,
    workspace_id UUID NOT NULL,
    correlation_key TEXT NOT NULL CHECK (length(correlation_key) = 64),
    generation BIGINT NOT NULL CHECK (generation > 0),
    service_key TEXT NOT NULL CHECK (length(service_key) BETWEEN 1 AND 160),
    environment TEXT NOT NULL CHECK (length(environment) BETWEEN 1 AND 80),
    title TEXT NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 1000),
    lifecycle_state TEXT NOT NULL CHECK (lifecycle_state IN ('open', 'needs_human', 'recovering', 'recovered', 'retired')),
    severity TEXT NOT NULL CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    action_required BOOLEAN NOT NULL DEFAULT FALSE,
    next_step TEXT NOT NULL CHECK (length(btrim(next_step)) BETWEEN 1 AND 500),
    verification_state TEXT NOT NULL CHECK (verification_state IN ('unverified', 'observed', 'verified')),
    project_id UUID,
    linked_issue_id UUID,
    opened_at TIMESTAMPTZ NOT NULL,
    last_observed_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE company_signal_event (
    workspace_id UUID NOT NULL,
    source_key TEXT NOT NULL CHECK (length(source_key) BETWEEN 1 AND 100),
    event_id TEXT NOT NULL CHECK (length(event_id) BETWEEN 1 AND 240),
    request_hash TEXT NOT NULL CHECK (length(request_hash) = 64),
    contract_version INTEGER NOT NULL CHECK (contract_version = 1),
    source_system TEXT NOT NULL CHECK (length(source_system) BETWEEN 1 AND 100),
    source_instance TEXT NOT NULL CHECK (length(source_instance) BETWEEN 1 AND 160),
    source_native_id TEXT NOT NULL CHECK (length(source_native_id) BETWEEN 1 AND 240),
    source_revision TEXT NOT NULL CHECK (length(source_revision) BETWEEN 1 AND 160),
    event_kind TEXT NOT NULL CHECK (event_kind IN ('availability', 'application_log', 'support_report', 'deployment', 'verification')),
    source_lane TEXT NOT NULL CHECK (source_lane IN ('availability', 'application_logs', 'support_impact', 'deployment', 'verification')),
    lifecycle_state TEXT NOT NULL CHECK (lifecycle_state IN ('new', 'worsened', 'needs_human', 'recovering', 'recovered', 'suppressed', 'retired')),
    severity TEXT NOT NULL CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    action_required BOOLEAN NOT NULL,
    summary TEXT NOT NULL CHECK (length(btrim(summary)) BETWEEN 1 AND 1000),
    next_step TEXT NOT NULL CHECK (length(btrim(next_step)) BETWEEN 1 AND 500),
    affected_refs JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(affected_refs) = 'array'),
    service_key TEXT NOT NULL CHECK (length(service_key) BETWEEN 1 AND 160),
    environment TEXT NOT NULL CHECK (length(environment) BETWEEN 1 AND 80),
    project_ref TEXT,
    outcome_ref TEXT,
    evidence_refs JSONB NOT NULL CHECK (jsonb_typeof(evidence_refs) = 'array'),
    predecessor_event_id TEXT,
    privacy_class TEXT NOT NULL CHECK (privacy_class IN ('internal', 'confidential', 'restricted')),
    raw_payload_hash TEXT NOT NULL CHECK (length(raw_payload_hash) = 64),
    correlation_key TEXT NOT NULL CHECK (length(correlation_key) = 64),
    incident_generation BIGINT NOT NULL CHECK (incident_generation > 0),
    incident_id UUID NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    state TEXT NOT NULL DEFAULT 'received' CHECK (state IN ('received', 'applied', 'rejected')),
    result JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(result) = 'object'),
    error_code TEXT,
    applied_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE company_signal_quarantine (
    id UUID NOT NULL,
    workspace_id UUID NOT NULL,
    source_key TEXT NOT NULL,
    event_id TEXT NOT NULL,
    stored_request_hash TEXT NOT NULL CHECK (length(stored_request_hash) = 64),
    received_request_hash TEXT NOT NULL CHECK (length(received_request_hash) = 64),
    reason_code TEXT NOT NULL CHECK (length(reason_code) BETWEEN 1 AND 100),
    received_payload JSONB NOT NULL CHECK (jsonb_typeof(received_payload) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
