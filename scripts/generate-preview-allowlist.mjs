#!/usr/bin/env node
// Regenerates packages/views/editor/utils/preview-allowlist.ts from
// server/internal/handler/preview_allowlist.json (the single source of truth).
//
// Run via `pnpm generate:preview-allowlist`. CI re-runs the generator and
// `git diff --exit-code`s the output, so the JSON and TS sides cannot drift.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(repoRoot, "server/internal/handler/preview_allowlist.json");
const tsPath = resolve(repoRoot, "packages/views/editor/utils/preview-allowlist.ts");

const raw = readFileSync(jsonPath, "utf8");
const data = JSON.parse(raw);

if (!Array.isArray(data.extensions)) {
  throw new Error(`preview_allowlist.json: expected top-level "extensions" array`);
}
if (!Array.isArray(data.contentTypes)) {
  throw new Error(`preview_allowlist.json: expected top-level "contentTypes" array`);
}
if (!Array.isArray(data.basenames)) {
  throw new Error(`preview_allowlist.json: expected top-level "basenames" array`);
}

function validateStringArray(arr, fieldName) {
  const seen = new Set();
  for (const entry of arr) {
    if (typeof entry !== "string" || entry.length === 0) {
      throw new Error(`preview_allowlist.json: ${fieldName} entries must be non-empty strings`);
    }
    if (seen.has(entry)) {
      throw new Error(`preview_allowlist.json: duplicate entry ${JSON.stringify(entry)} in ${fieldName}`);
    }
    seen.add(entry);
  }
}

validateStringArray(data.extensions, "extensions");
validateStringArray(data.contentTypes, "contentTypes");
validateStringArray(data.basenames, "basenames");

const lines = [];
lines.push("// AUTO-GENERATED by scripts/generate-preview-allowlist.mjs.");
lines.push("// Do not edit by hand — edit server/internal/handler/preview_allowlist.json");
lines.push("// and run `pnpm generate:preview-allowlist`.");
lines.push("");

lines.push("export const TEXT_EXTENSIONS: ReadonlySet<string> = new Set([");
for (const ext of data.extensions) {
  lines.push(`  ${JSON.stringify(ext)},`);
}
lines.push("]);");
lines.push("");

lines.push("export const TEXT_CONTENT_TYPES: ReadonlySet<string> = new Set([");
for (const ct of data.contentTypes) {
  lines.push(`  ${JSON.stringify(ct)},`);
}
lines.push("]);");
lines.push("");

lines.push("export const TEXT_BASENAMES: ReadonlySet<string> = new Set([");
for (const b of data.basenames) {
  lines.push(`  ${JSON.stringify(b)},`);
}
lines.push("]);");
lines.push("");

writeFileSync(tsPath, lines.join("\n"));
console.log(`Written: ${tsPath}`);
